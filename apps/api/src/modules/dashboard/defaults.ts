const defaults: Record<CatalogScope, DashboardDefinition> = {
  global: validateDefinition({ version: 3, widgets: globalWidgets }, "global"),
  organization: validateDefinition(
    { version: 3, widgets: organizationWidgets },
    "organization",
  ),
};

/**
 * Real-data starter layout returned while the account has not saved one.
 * Version 3 native grid geometry and revision 0 are explicit; reading never
 * writes this to the database.
 */
export function defaultDashboardDefinition(
  scope: CatalogScope,
): DashboardDefinition {
  return {
    version: 3,
    widgets: defaults[scope].widgets.map((widget) => ({
      ...widget,
      filters: { statuses: [...widget.filters.statuses] },
    })),
  };
}

export function dashboardScope(organizationId: string | null): CatalogScope {
  return organizationId === null ? "global" : "organization";
}
